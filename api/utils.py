"""Вспомогательные функции приложения api."""


def capitalize_title(value: str) -> str:
    """Привести заголовок к виду «Каждое Слово С Большой Буквы» (Title Case).

    Используется при добавлении и изменении курсов и категорий через API:

        "python basics"   -> "Python Basics"
        "  django   drf " -> "Django Drf"

    Пробелы по краям и повторяющиеся пробелы внутри заголовка убираются.
    Поведение повторяет str.title(), поэтому слова с апострофом или дефисом
    капитализируются по границе небуквенного символа: "don't" -> "Don'T".
    """
    return " ".join(value.split()).title()
